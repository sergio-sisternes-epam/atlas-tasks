#!/usr/bin/env python3
"""atlas-tasks: write or refresh index.md in every non-root task-list folder.

Atlas compile warns `index_md_present` for any folder holding concept pages
without an index.md. atlas-tasks v0.7.0 keeps a generated directory listing
in each non-root list folder. This helper backfills and refreshes it.

Usage:
  list-folder-index.py --root <atlas-root> [--dry-run] [--list <ULID>]

- Discovery walks pointers from tasks/index.md only (pin 20); no store scan.
- Idempotent: rewrites a file only when its generated content changes.
- Only touches index.md files it owns (frontmatter `generated_by: atlas-tasks`)
  or that do not exist. A hand-written index.md is reported and left alone.
- Never deletes anything.
Exit: 0 ok (or nothing to do); 1 an unresolved member/pointer (root included),
      invalid list frontmatter, or an unreachable --list selector; 2 usage.
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
import tempfile
from pathlib import Path

try:
    import yaml
except ImportError:  # fail closed: never guess membership with a hand parser
    print("error: PyYAML is required (pip install pyyaml)", file=sys.stderr)
    sys.exit(2)


class FrontmatterError(ValueError):
    pass

MARKER = "atlas-tasks"
ULID_RE = re.compile(r"/tasks/([0-9A-HJKMNP-TV-Z]{26})$")


def frontmatter(text: str) -> tuple[dict, str]:
    """Parse YAML frontmatter with a real YAML parser (block or flow sequences)."""
    m = re.match(r"^---\n(.*?)\n---\n?", text, re.S)
    if not m:
        return {}, text
    try:
        meta = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as e:
        raise FrontmatterError(f"invalid YAML frontmatter: {e}") from e
    if not isinstance(meta, dict):
        raise FrontmatterError("frontmatter is not a mapping")
    return meta, text[m.end():]


def members_of(meta: dict, where: str) -> list[str]:
    """`tasks` must be a sequence of member URI strings (absent/null = empty)."""
    raw = meta.get("tasks")
    if raw is None:
        return []
    if not isinstance(raw, list) or not all(isinstance(x, str) for x in raw):
        raise FrontmatterError(f"{where}: `tasks` must be a list of atlas:// URIs")
    return [x.strip() for x in raw]


def yq(value: object) -> str:
    """YAML single-quoted scalar: backslashes stay literal, apostrophes doubled."""
    return "'" + str(value).replace("'", "''") + "'"


def ulid_of(uri: str) -> str | None:
    m = ULID_RE.search(str(uri).strip())
    return m.group(1) if m else None


def contained(root: Path, p: Path) -> bool:
    """True when p is not a symlink and its resolved path stays inside root."""
    if p.is_symlink():
        return False
    try:
        p.resolve().relative_to(root)
    except ValueError:
        return False
    return True


def find_member(root: Path, folder: Path, ulid: str) -> tuple[Path, str] | None:
    """Member inside an already-reached list folder: task file or child list folder (ULID prefix).
    Symlinks and anything resolving outside root are never followed (no writes outside --root)."""
    for p in sorted(folder.iterdir()):
        if not p.name.startswith(ulid) or not contained(root, p):
            continue
        if p.is_dir():
            for f in sorted(p.glob(f"{ulid}*.task-list.md")):
                if contained(root, f):
                    return f, "list"
        elif p.suffix == ".md" and not p.name.endswith(".task-list.md"):
            return p, "task"
    return None


def render(list_file: Path, meta: dict, rows: list[tuple[str, str, str, str]]) -> str:
    title = meta.get("title") or list_file.stem
    lines = [
        "---",
        f"title: {yq('Index: ' + str(title))}",
        f"description: {yq('Directory listing for task list ' + (ulid_of(str(meta.get('task_id', ''))) or '') + '. Generated by atlas-tasks; the list page is authoritative.')}",
        f"generated_by: {MARKER}",
        f"task_list_page: {yq(list_file.name)}",
        "origin: derived",
        "sensitivity: internal",
        "---",
        "",
        f"# {title}",
        "",
        f"Task list page: [{list_file.name}]({list_file.name}). Membership lives in its `tasks` frontmatter; this index is a generated listing only.",
        "",
        "## Members",
        "",
    ]
    if not rows:
        lines.append("_No members yet._")
    for ulid, kind, rel, label in rows:
        if rel:
            lines.append(f"- [{label}]({rel}) — `{ulid}` ({kind})")
        else:
            lines.append(f"- `{ulid}` — not found in this folder (unresolved)")
    return "\n".join(lines) + "\n"


def _copy_tree_nofollow(root: Path, src: Path, dst: Path) -> None:
    """Copy a directory tree without following symlinks or leaving root."""
    dst.mkdir(parents=True, exist_ok=True)
    for child in src.iterdir():
        if child.is_symlink() or not contained(root, child):
            continue
        target = dst / child.name
        if child.is_dir():
            _copy_tree_nofollow(root, child, target)
        elif child.is_file():
            target.write_bytes(child.read_bytes())


def render_list_folder_index(
    root: Path,
    list_rel: str,
    overlay: dict[str, str | None] | None = None,
) -> tuple[str, str | None]:
    """Return ``(index_markdown, error)`` for one list folder after ``overlay``.

    ``overlay`` maps store-relative paths to replacement text, or None to delete.
    The markdown is exactly what ``render`` / ``find_member`` / ``frontmatter``
    produce for that folder (same path the CLI uses). A temporary snapshot is
    used so the walk sees post-overlay paths; nothing is written under ``root``.
    ``error`` is set when the list file is missing or a member does not resolve.
    """
    root = root.resolve()
    list_rel = list_rel.replace("\\", "/").lstrip("/")
    folder_rel = str(Path(list_rel).parent).replace("\\", "/")
    overlay = overlay or {}
    tmp = tempfile.mkdtemp(prefix="atlas-tasks-idx-")
    try:
        snap = Path(tmp).resolve()
        src = root / folder_rel
        if src.exists():
            if src.is_symlink() or not contained(root, src):
                return "", f"{folder_rel}: symlink or path outside root"
            _copy_tree_nofollow(root, src, snap / folder_rel)
        prefix = folder_rel.rstrip("/") + "/"
        for rel, content in overlay.items():
            rel = str(rel).replace("\\", "/")
            if rel != list_rel and not rel.startswith(prefix):
                continue
            dest = snap / rel
            if any(part.is_symlink() for part in dest.parents if part != snap and snap in part.parents):
                return "", f"{rel}: symlink"
            if content is None:
                if dest.is_symlink():
                    return "", f"{rel}: symlink"
                if dest.is_file():
                    dest.unlink()
                continue
            if dest.is_symlink():
                return "", f"{rel}: symlink"
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content, encoding="utf-8")
        list_file = snap / list_rel
        if not list_file.is_file() or list_file.is_symlink():
            return "", f"{list_rel}: list file missing after overlay"
        try:
            meta, _body = frontmatter(list_file.read_text(encoding="utf-8"))
            uris = members_of(meta, list_rel)
        except FrontmatterError as e:
            return "", str(e)
        folder = list_file.parent
        rows: list[tuple[str, str, str, str]] = []
        for uri in uris:
            u = ulid_of(uri)
            hit = find_member(snap, folder, u) if u else None
            if hit is None:
                return "", f"{list_rel}: member {uri} not resolved in {folder_rel}/"
            path, kind = hit
            try:
                m2, _b = frontmatter(path.read_text(encoding="utf-8"))
            except FrontmatterError as e:
                return "", f"{path.name}: {e}"
            rows.append((u or "", kind, path.relative_to(folder).as_posix(), m2.get("title") or path.stem))
        return render(list_file, meta, rows), None
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", required=True)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--list", dest="only", default=None, help="only this list ULID")
    a = ap.parse_args(argv)
    root = Path(a.root).resolve()
    rootidx = root / "tasks" / "index.md"
    if not rootidx.is_file():
        print(f"error: {rootidx} missing", file=sys.stderr)
        return 2
    rc = 0
    seen: set[str] = set()
    reached_only = False
    counts = {"create": 0, "update": 0, "ok": 0, "skip-foreign": 0, "unresolved": 0}
    try:
        stack: list[tuple[Path, dict]] = [(rootidx, frontmatter(rootidx.read_text(encoding="utf-8"))[0])]
    except FrontmatterError as e:
        print(f"error: tasks/index.md: {e}", file=sys.stderr)
        return 1
    while stack:
        lf, meta = stack.pop(0)
        folder = lf.parent
        lrel = lf.relative_to(root).as_posix()
        rows = []
        try:
            uris = members_of(meta, lrel)
        except FrontmatterError as e:
            print(f"error: {e}", file=sys.stderr)
            rc = 1
            continue
        for uri in uris:
            u = ulid_of(uri)
            hit = find_member(root, folder, u) if u else None
            m2: dict = {}
            if hit is not None:
                try:
                    m2 = frontmatter(hit[0].read_text(encoding="utf-8"))[0]
                except FrontmatterError as e:
                    print(f"error: {hit[0].relative_to(root)}: {e}", file=sys.stderr)
                    hit = None
            if hit is None:
                # Fail closed: an unresolved pointer may hide a whole subtree (root included).
                counts["unresolved"] += 1
                rc = 1
                print(f"error: {lrel}: member {uri} not resolved in {folder.relative_to(root).as_posix()}/", file=sys.stderr)
                rows.append((u or str(uri), "?", "", ""))
                continue
            path, kind = hit
            rows.append((u, kind, path.relative_to(folder).as_posix(), m2.get("title") or path.stem))
            if kind == "list" and u not in seen:
                seen.add(u)
                stack.append((path, m2))
        if lf == rootidx:
            continue  # root keeps reserved tasks/index.md itself (pin 18/21)
        lu = ulid_of(str(meta.get("task_id", ""))) or ""
        if a.only and lu != a.only:
            continue
        reached_only = reached_only or bool(a.only)
        target = folder / "index.md"
        new = render(lf, meta, rows)
        rel = target.relative_to(root)
        if not contained(root, folder) or (target.exists() or target.is_symlink()) and not contained(root, target):
            print(f"error: {rel}: symlink or path outside --root; not written", file=sys.stderr)
            rc = 1
            continue
        if target.exists():
            old = target.read_text(encoding="utf-8")
            try:
                owned = frontmatter(old)[0].get("generated_by") == MARKER
            except FrontmatterError:
                owned = False
            if not owned:
                counts["skip-foreign"] += 1
                print(f"skip  {rel} (hand-written index.md, not owned by atlas-tasks)")
                continue
            if old == new:
                counts["ok"] += 1
                print(f"ok    {rel}")
                continue
            action = "update"
        else:
            action = "create"
        counts[action] += 1
        print(f"{'would ' if a.dry_run else ''}{action} {rel}")
        if not a.dry_run:
            target.write_text(new, encoding="utf-8")
    if a.only and not reached_only:
        print(f"error: --list {a.only} is not a non-root task list reachable from tasks/index.md", file=sys.stderr)
        rc = 1
    print("summary: " + ", ".join(f"{k}={v}" for k, v in counts.items()) + (" (dry run)" if a.dry_run else ""))
    return rc


if __name__ == "__main__":
    sys.exit(main())
